/** Текст ответа бота на ошибку сценария. */
export function botErrorText(error: unknown): string {
  if (!(error instanceof ApiError)) return FRIENDLY.INTERNAL!;
  const isDefault = error.message === ERROR_MESSAGES[error.code];
  const main = isDefault
    ? FRIENDLY[error.code] ?? esc(ERROR_MESSAGES[error.code])
    : esc(error.message);
  return `${main}\n${esc("/help")} — все команды / барлық командалар`;
}
