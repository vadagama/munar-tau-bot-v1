import type { Row } from "../../src/domains/registry/validation.ts";
import { it } from "vitest";
import assert from "node:assert/strict";
import { describeWithDb } from "./with-db.ts";
import { setupTasks } from "./tasks-helpers.ts";
import { staffRequestStep, type StaffReply } from "../../src/bot/staff-requests.ts";
import { queueRequestFile } from "../../src/bot/request-files.ts";
import { almatyDay } from "../../src/bot/visit-time.ts";
import { transitionTask } from "../../src/domains/tasks/service.ts";
import { submitTaskReport } from "../../src/domains/tasks/reports.ts";
import { createRequest, transitionRequest } from "../../src/domains/requests/service.ts";
import { addMessage } from "../../src/domains/requests/messages.ts";
import { staffTimeline, markStaffRead } from "../../src/domains/requests/staff-timeline.ts";
import { listStaffRequests } from "../../src/domains/requests/staff-queries.ts";

describeWithDb("Staff request bot", getDb => {
 it("completes the work cycle and preserves file audience and read boundaries", async () => {
 type Sample={id:string;version:number;state:string;confirmation_version:number;n:number;full_name:string;bucket:string;channel:string};
 const db=getDb();
const {deps,admin,worker,request}=await setupTasks(db);
let reply!: StaffReply; const step=async(input: string)=>reply=await staffRequestStep(deps,'-1',input,admin);
const press=async(label: string)=>{const b=reply.buttons.flat().find(b=>b.text===label);assert.ok(b,`missing button ${label}: ${JSON.stringify(reply)}`);return step(b.data);};
await step('/staffrequest '+request.number);
await press('Взять на рассмотрение');await press('Подтвердить');
await press('Начать работу');
const name=(await db.query<Sample>('select full_name from person where id=$1',[worker.person.id]))[0]!.full_name;
await press(name);await step('Проверить и заменить кран');await step(almatyDay(7)+' 12:00');
assert.ok(reply.text.includes(name));await press('Подтвердить');
let task=(await db.query<Sample>('select * from task where request_id=$1',[request.id]))[0]!;assert.equal(task.state,'awaiting_acceptance');
await transitionTask(deps,worker,String(task.id),{action:'accept',version:task.version},'accept');
task=(await db.query<Sample>('select * from task where id=$1',[task.id]))[0]!;await transitionTask(deps,worker,String(task.id),{action:'start',version:task.version},'start');
task=(await db.query<Sample>('select * from task where id=$1',[task.id]))[0]!;await submitTaskReport(deps,worker,String(task.id),{version:task.version,performed_work:'Заменён кран',performed_at:new Date().toISOString(),result:'Протечки нет',limitations:'',evidence:[]},'report');
await step('/start stsk_'+task.id);await press('Принять отчёт');await press('Подтвердить');
assert.equal((await db.query<Sample>('select state from task where id=$1',[task.id]))[0]!.state,'accepted_admin');
await step('/staffrequest '+request.number);await press('Передать результат жителю');await step('Кран заменён, протечки нет.');const confirm=reply.buttons.flat().find(b=>b.text==='Подтвердить')!.data;await step(confirm);await step(confirm);
const current=(await db.query<Sample>('select * from request where id=$1',[request.id]))[0]!;assert.equal(current.state,'awaiting_confirmation');
await transitionRequest(deps,worker,String(request.id),{action:'confirm_result',expected_version:current.version,payload:{confirmation_version:current.confirmation_version}},'confirm');
assert.equal((await db.query<Sample>('select state from request where id=$1',[request.id]))[0]!.state,'closed');
assert.equal((await db.query<Sample>('select count(*)::int n from task where request_id=$1',[request.id]))[0]!.n,1);
const second=await createRequest(deps,worker,{text:'Ещё одна проблема',source:'bot',premises_id:request.premises_id},'request-2');
const beforeMessages=(await db.query<Sample>('select count(*)::int n from message where request_id=$1',[second.id]))[0]!.n;
await step('/staffrequest '+second.number);await press('Внутренняя заметка');
await queueRequestFile(deps,'-1',{document:{file_id:'test-file',file_name:'internal.pdf',mime_type:'application/pdf',file_size:1024},caption:'Внутренний материал'},500,'worker');
const file=(await db.query<Sample>("select * from attachment where request_id=$1",[second.id]))[0]!;assert.equal(file.bucket,'internal');
assert.equal((await db.query<Sample>('select count(*)::int n from message where request_id=$1',[second.id]))[0]!.n,beforeMessages);
const context=(await db.query<{state:Row}>("select state from bot_dialog_channel where bot='worker' and telegram_user_id=-1"))[0]!.state;
await step(`/sr ${context.token} review`);await press('Подтвердить');assert.ok(reply.text.includes('сохраняются'));
await db.query<Sample>("update attachment set status='complete' where id=$1",[file.id]);await press('Подтвердить');
assert.equal((await db.query<Sample>("select channel from message where request_id=$1 and channel='internal'",[second.id]))[0]!.channel,'internal');
await addMessage(deps,worker,String(second.id),{text:'Ответ жителя',channel:'resident'},'resident-1');
const viewed=await staffTimeline(db,admin,String(second.id),'messages');const displayed=viewed.items.filter(m=>m.incoming&&m.channel==='resident').map(m=>m.id);assert.equal(displayed.length,beforeMessages+1);
await addMessage(deps,worker,String(second.id),{text:'Новое сообщение после открытия страницы',channel:'resident'},'resident-2');
await markStaffRead(db,admin,String(second.id),displayed);
assert.equal((await db.query<Sample>('select count(*)::int n from request_message_read'))[0]!.n,displayed.length);
assert.ok((await listStaffRequests(db,admin,{queue:'attention'})).items.some(r=>r.id===second.id&&r.unread));
await assert.rejects(staffTimeline(db,worker,String(second.id),'messages'),(e: unknown)=>!!e && typeof e==='object' && 'code' in e && e.code==='FORBIDDEN');

 });
});
